"""Export the best trained YOLO run to ONNX + TFLite and install it into the app.

Usage (from project root):
    .venv\\Scripts\\python.exe scripts\\export_windows.py            # auto-pick best run
    .venv\\Scripts\\python.exe scripts\\export_windows.py <best.pt>  # explicit weights

Outputs:
    src/assets/models/indoor_yolov8n.tflite   (float32, input [1,640,640,3] NHWC)
    src/assets/models/indoor_yolov8n.onnx
    src/assets/models/indoor_yolov8n.labels.ts (class names in model index order)
"""
import json
import shutil
import sys
from pathlib import Path

from ultralytics import YOLO

sys.path.insert(0, str(Path(__file__).resolve().parent))
from best_run import find_best_run  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = PROJECT_ROOT / "src" / "assets" / "models"
IMGSZ = 640


def resolve_weights() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    found = find_best_run()
    if not found:
        sys.exit("Error: no completed training run with results.csv + weights/best.pt found.")
    weights, score, name = found
    print(f"Auto-selected run '{name}' (final mAP50-95 = {score:.4f})")
    return weights


def write_labels(names: dict, out_path: Path):
    ordered = [names[i] for i in sorted(names)]
    body = ",\n".join(f"  {n!r}" for n in ordered)
    out_path.write_text(
        "// AUTO-GENERATED by scripts/export_windows.py — do not edit by hand.\n"
        "// Index i is the class id emitted by indoor_yolov8n.tflite.\n"
        f"export const NUM_CLASSES = {len(ordered)};\n"
        f"export const MODEL_LABELS: readonly string[] = [\n{body}\n];\n",
        encoding="utf-8",
    )


def export_model():
    weights_path = resolve_weights()
    if not weights_path.exists():
        sys.exit(f"Error: Could not find weights at {weights_path}")

    print(f"Loading trained model from {weights_path}...")
    model = YOLO(str(weights_path))
    nc = len(model.names)
    print(f"Model has {nc} classes -> output tensor [1, {4 + nc}, 8400]")

    MODELS_DIR.mkdir(parents=True, exist_ok=True)

    # 1. ONNX
    print("Exporting ONNX...")
    onnx_file = Path(model.export(format="onnx", imgsz=IMGSZ, dynamic=False))
    shutil.copy2(onnx_file, MODELS_DIR / "indoor_yolov8n.onnx")

    # 2. TFLite via onnx2tf directly. Ultralytics >=8.4.83 routes format='tflite' to LiteRT,
    #    which refuses to run on Windows, so convert the ONNX ourselves.
    #    Result: input [1,640,640,3] NHWC float32; output [1, 4+nc, 8400] with boxes in 640-px space.
    import numpy as np
    import onnx2tf
    import onnx2tf.onnx2tf as _o2t

    # onnx2tf downloads a pickled sample-image .npy for its self-check, which numpy>=2 refuses to
    # load (allow_pickle=False). That data is only used for sanity checks, not for float32
    # conversion, so supply a local NHWC sample batch instead of downloading.
    _o2t.download_test_image_data = lambda: np.random.default_rng(0).random(
        (1, IMGSZ, IMGSZ, 3), dtype=np.float32
    )

    print("Converting ONNX -> TFLite (float32) with onnx2tf...")
    out_dir = weights_path.parent / "tflite_model"
    if out_dir.exists():
        shutil.rmtree(out_dir)
    onnx2tf.convert(
        input_onnx_file_path=str(onnx_file),
        output_folder_path=str(out_dir),
        non_verbose=True,
    )
    candidates = sorted(out_dir.glob("*_float32.tflite"))
    if not candidates:
        sys.exit(f"Error: onnx2tf produced no *_float32.tflite in {out_dir}")
    shutil.copy2(candidates[0], MODELS_DIR / "indoor_yolov8n.tflite")

    # 3. Labels for the app (TS for React Native, JSON for the browser viewfinder)
    write_labels(model.names, MODELS_DIR / "indoor_yolov8n.labels.ts")
    (MODELS_DIR / "indoor_yolov8n.labels.json").write_text(
        json.dumps([model.names[i] for i in sorted(model.names)]), encoding="utf-8"
    )

    print("\nSUCCESS! Installed into", MODELS_DIR)
    for f in ("indoor_yolov8n.tflite", "indoor_yolov8n.onnx", "indoor_yolov8n.labels.ts", "indoor_yolov8n.labels.json"):
        p = MODELS_DIR / f
        print(f"  {f:28s} {p.stat().st_size / 1e6:6.2f} MB")


if __name__ == "__main__":
    export_model()
